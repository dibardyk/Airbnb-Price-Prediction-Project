import pandas as pd
import numpy as np
import shutil
import json
import re
from pathlib import Path

SCRIPT_DIR = Path(__file__).parent
RAW_DIR = (SCRIPT_DIR / "../data/raw").resolve()
CLEAN_DIR = (SCRIPT_DIR / "../data/clean").resolve()

# Files that don't really need any cleaning
CLEAN_FILES = []

# id, reviewer_id, reviewer_name columns are probably irrelevant for ML
REVIEWS_KEEP = ["listing_id", "date", "comments"]

# Drop: 
# urls are not needed as we don't work with pictures
# scrape_id, last_scraped, source not important because just metadata
# host_name is not important, host_neighbourhood also (i did is_local_lost see below), host_total_listings_count are just basically repeating values, host_verifications is the list of different verifications (probably not that relevant if we have host_identity_verified)
# neighbourhood just says berlin, property_type is the same as room_type
# all the maximums and minimums are just redundant having just standart maximum and minimum nights
# calendar data is just metadata
# availability eoy, 60 and 90 pretty redundant with having availability 30 and 365
# number_of_reviews_l30d etc is redundant having the total amount for last 12 months, reviews_per_month is redundant having last 12 month because the price reflects the data of now and not the total average
# estimated_occupancy_l365d,estimated_revenue_l365d are generated by scraper and also contain the target variable
# first_review,last_review probably not that important
# reviews are pretty redundant with just overall review
# calculated... just redundant with total listings by host   
LISTINGS_DROP = ["listing_url", "picture_url", "host_url", "host_thumbnail_url", "host_picture_url",
            "scrape_id", "last_scraped", "source",
            "host_name", "host_neighbourhood", "host_total_listings_count", "host_verifications",
            "neighbourhood", "property_type",
            "minimum_minimum_nights", "maximum_minimum_nights","minimum_maximum_nights","maximum_maximum_nights", "minimum_nights_avg_ntm", "maximum_nights_avg_ntm",
            "calendar_updated", "calendar_last_scraped",
            "availability_60", "availability_90", "availability_eoy",
            "number_of_reviews_ly", "number_of_reviews_l30d", "reviews_per_month",
            "estimated_occupancy_l365d", "estimated_revenue_l365d",
            "first_review", "last_review",
            "review_scores_accuracy", "review_scores_cleanliness", "review_scores_checkin", "review_scores_communication", "review_scores_value",
            "calculated_host_listings_count","calculated_host_listings_count_entire_homes","calculated_host_listings_count_private_rooms","calculated_host_listings_count_shared_rooms"]

# Text data and descriptions that should be formatted 
TEXT_COLS = ["name", "description", "neighborhood_overview", "host_about"]

BOOL_COLS = ["host_is_superhost", "host_has_profile_pic", "host_identity_verified", "has_availability", "instant_bookable"]

RATE_COLS = ["host_response_rate", "host_acceptance_rate"]

TIME_MAPPING = {
            "within an hour": 4,
            "within a few hours": 3,
            "within a day": 2,
            "a few days or more": 1
        }

COUNT_COLS = ["host_listings_count", "accommodates", "bedrooms", "beds"]

COLUMN_RENAMES = {
    "id": "listing_id",
    "host_is_superhost": "is_superhost",
    "host_has_profile_pic": "host_has_pic",
    "host_identity_verified": "is_host_verified",
    "host_response_time_score": "response_time_score",
    "neighbourhood_cleansed": "neighborhood",
    "neighbourhood_group_cleansed": "neighborhood_group",
    "minimum_nights": "min_nights",
    "maximum_nights": "max_nights",
    "availability_30": "avail_30",
    "availability_365": "avail_365",
    "number_of_reviews": "total_reviews",
    "number_of_reviews_ltm": "reviews_last_12m",
    "review_scores_rating": "rating_overall",
    "review_scores_location": "rating_location",
    "room_type_Entire home/apt": "room_type_entire_home",
    "room_type_Hotel room": "room_type_hotel",
    "room_type_Private room": "room_type_private",
    "room_type_Shared room": "room_type_shared",
    "bathrooms_numeric": "bathrooms"
}

GEOJSON_PROPERTY_RENAMES = {"neighbourhood": "neighborhood", "neighbourhood_group": "neighborhood_group"}


def clean_text(text):
    return (text.fillna("")
                  .astype(str)
                  .str.replace(r"<[^>]+>", " ", regex=True)
                  .str.replace(r"\s+", " ", regex=True)
                  .str.strip())


def copy_files(src_dir=RAW_DIR, dst_dir=CLEAN_DIR):
    for filename in CLEAN_FILES:
        src = src_dir / filename
        dst = dst_dir / filename
        
        if src.exists():
            shutil.copy(src, dst)
            print(f"Copied without changes: {filename}")
        else:
            print(f"Error: {filename} not found in {RAW_DIR}")


def normalize_geo_name(value):
    if value is None or (isinstance(value, float) and np.isnan(value)):
        return value
    return re.sub(r"\s+", " ", str(value)).strip()


def clean_geojson(file_path):
    print(f"Cleaning: {file_path.name}...")
    with open(file_path, "r", encoding="utf-8") as f:
        geo = json.load(f)

    for feature in geo["features"]:
        props = feature.get("properties", {})
        cleaned_props = {}
        for key, value in props.items():
            new_key = GEOJSON_PROPERTY_RENAMES.get(key, key)
            if isinstance(value, str):
                value = normalize_geo_name(value)
            cleaned_props[new_key] = value
        feature["properties"] = cleaned_props

    return geo


def save_geojson(geo, dst_path):
    with open(dst_path, "w", encoding="utf-8") as f:
        json.dump(geo, f, ensure_ascii=False)


def clean_reviews(file_path):
    print(f"Cleaning: {file_path.name}...")
    df = pd.read_csv(file_path)
    df = df[REVIEWS_KEEP]
    
    # If comments are missing the entry is irrelevant
    df = df.dropna(subset=["comments"])
    df["date"] = pd.to_datetime(df["date"])
    
    # Formatting the comments
    df["comments"] = clean_text(df["comments"])
    
    return df


def clean_listings(file_path):
    print(f"Cleaning: {file_path.name}...")
    df = pd.read_csv(file_path, low_memory=False)
    
    if "last_scraped" in df.columns:
        reference_date = pd.to_datetime(df["last_scraped"], errors="coerce").max()
    else:
        reference_date = pd.Timestamp.today().normalize()
    
    cols_to_drop = [col for col in LISTINGS_DROP if col in df.columns]
    df = df.drop(columns=cols_to_drop)
    
    # Text data and descriptions that should be formatted 
    for col in TEXT_COLS:
        if col in df.columns:
            # Empty descriptions are filled with "" (can be changed to "No description" or something)
            df[col] = clean_text(df[col])
    
    if "neighbourhood_cleansed" in df.columns:
        df["neighbourhood_cleansed"] = df["neighbourhood_cleansed"].str.replace(r"\s+", " ", regex=True)
    
    # Only really relevant if the host is local or not, so change it if Berlin is mentioned
    if "host_location" in df.columns:
        df["host_location"] = df["host_location"].fillna("")
        df["is_local_host"] = df["host_location"].str.contains("Berlin", case=False).astype(int)
        df = df.drop(columns=["host_location"])

    # The experience of host may be relevant
    if "host_since" in df.columns:
        df["host_since"] = pd.to_datetime(df["host_since"], errors="coerce")
        
        # Calculate the number of days being a host with last scraped date
        df["host_since_days"] = (reference_date - df["host_since"]).dt.days
        
        df["host_since_days"] = df["host_since_days"].astype("Int64")
        df = df.drop(columns=["host_since"])
    
    # Convert all boolean to 1,0. For missing values assume 0
    for col in BOOL_COLS:
        if col in df.columns:
            df[col] = df[col].isin(["t", "true", "True", True, 1.0, 1, "1", "1.0"]).astype(int)
    
    if "room_type" in df.columns:
        df = pd.get_dummies(df, columns=["room_type"], dtype=int)
    
    # Convert percentages to floats
    for col in RATE_COLS:
        if col in df.columns:
            df[col] = df[col].astype(str).replace(["N/A", "nan", "<NA>"], pd.NA)
            df[col] = df[col].str.replace("%", "", regex=False)
            df[col] = pd.to_numeric(df[col], errors="coerce")

    # Categorizing response time as numbers
    if "host_response_time" in df.columns:
        df["host_response_time_score"] = df["host_response_time"].map(TIME_MAPPING)
        df["host_response_time_score"] = df["host_response_time_score"].fillna(0).astype(int)
        df = df.drop(columns=["host_response_time"])
        
    # Convert counts to numeric and assume 1 with missing
    for col in COUNT_COLS:
        if col in df.columns:
            df[col] = pd.to_numeric(df[col], errors="coerce").fillna(1).astype(int)
    
    # Format coordinates
    for col in ["latitude", "longitude"]:
        if col in df.columns:
            df[col] = pd.to_numeric(df[col], errors="coerce")
            
    # Extract numeric values from bathrooms_text, because some are missing
    if "bathrooms_text" in df.columns:
        df["bathrooms_numeric"] = df["bathrooms_text"].astype(str).str.extract(r"(\d+\.?\d*)").astype(float)
        df["bathrooms_numeric"] = df["bathrooms_numeric"].fillna(1.0)
        df = df.drop(columns=["bathrooms_text", "bathrooms"], errors="ignore")
    
    # Replaced lists of features like wifi etc with just the count of them, that can be easily used (creating a column for each one would really be overbloating)
    if "amenities" in df.columns:
        stripped = df["amenities"].fillna("").str.strip("[]")
        df["amenities_count"] = np.where(stripped == "", 0, stripped.str.split(",").str.len()).astype(int)
        df = df.drop(columns=["amenities"])
    
    # Formatting price and dropping the rows entirely that don't have it (useless because it is the target), and adding the log_price column
    if "price" in df.columns:
        df["price"] = df["price"].astype(str).str.replace(r"[\$,]", "", regex=True)
        df["price"] = pd.to_numeric(df["price"], errors="coerce")
        
        df = df.dropna(subset=["price"])
        df = df[df["price"] > 0]
        
        df["log_price"] = np.log1p(df["price"])
        
    # Formatting minimum and maximum nights
    for col in ["minimum_nights", "maximum_nights"]:
        if col in df.columns:
            df[col] = pd.to_numeric(df[col], errors="coerce")
            if col == "minimum_nights":
                df[col] = df[col].fillna(1).astype(int)
            else:
                df[col] = df[col].fillna(365).astype(int)
    
    # Dealing with long term listings: everything above a month is considered long term, 
    # extreme values are capped as they mean the same thing mostly
    if "minimum_nights" in df.columns:
        df["is_long_term"] = (df["minimum_nights"] >= 28).astype(int)
        df["minimum_nights"] = df["minimum_nights"].clip(upper=365)
        df["log_min_nights"] = np.log1p(df["minimum_nights"])
    
    for col in ["availability_30", "availability_365", "number_of_reviews", "number_of_reviews_ltm"]:
        if col in df.columns:
            df[col] = pd.to_numeric(df[col], errors="coerce").fillna(0).astype(int)
    
    for col in ["review_scores_rating", "review_scores_location"]:
        if col in df.columns:
            df[col] = pd.to_numeric(df[col], errors="coerce")
    if "review_scores_rating" in df.columns:
        df["rating_is_missing"] = df["review_scores_rating"].isna().astype(int)
            
    # If there is some kind of a license it has a license.. so just boolean
    if "license" in df.columns:
        df["has_license"] = df["license"].notna().astype(int) 
        df = df.drop(columns=["license"])
    
    df = df.rename(columns=COLUMN_RENAMES)
    
    return df


def clean_data():
    CLEAN_DIR.mkdir(parents=True, exist_ok=True)
    
    copy_files()

    geojson_path = RAW_DIR / "neighbourhoods.geojson"
    if geojson_path.exists():
        cleaned_geo = clean_geojson(geojson_path)
        save_geojson(cleaned_geo, CLEAN_DIR / "neighbourhoods.geojson")
        print(f"neighbourhoods.geojson saved to {CLEAN_DIR.name}")

    reviews_path = RAW_DIR / "reviews.csv"
    if reviews_path.exists():
        cleaned_reviews = clean_reviews(reviews_path)
        cleaned_reviews.to_csv(CLEAN_DIR / "reviews.csv", index=False)
        print(f"reviews.csv saved to {CLEAN_DIR.name}")
        
    listings_path = RAW_DIR / "listings.csv"
    if listings_path.exists():
        cleaned_listings = clean_listings(listings_path)
        cleaned_listings.to_csv(CLEAN_DIR / "listings.csv", index=False)
        print(f"listings.csv saved to {CLEAN_DIR.name}")
